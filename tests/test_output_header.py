from customize_daemonset import (
    format_output_header,
    text_is_generated_output,
)


TOTALS = {
    "pods": 3,
    "cpu_request_millis": 1600,
    "cpu_limit_millis": 6000,
    "mem_request_mi": 3392,   # 3392 / 1024 = 3.3125 Gi
    "mem_limit_mi": 6784,
}


def test_header_is_all_comment_lines():
    header = format_output_header(command="customize-daemonset --base b.yaml",
                                  totals=TOTALS)
    lines = header.splitlines()
    assert lines, "header should not be empty"
    assert all(line.startswith("#") for line in lines)


def test_header_contains_generated_marker():
    header = format_output_header(command="customize-daemonset", totals=TOTALS)
    assert "Generated by customize-daemonset" in header


def test_header_embeds_command_across_continuations():
    cmd = "customize-daemonset --base b.yaml \\\n    --tolerate-all"
    header = format_output_header(command=cmd, totals=TOTALS)
    assert "customize-daemonset --base b.yaml" in header
    assert "--tolerate-all" in header


def test_header_reports_pods_and_post_scaling_totals():
    header = format_output_header(command="customize-daemonset", totals=TOTALS)
    assert "3 pods" in header
    assert "1.60 cores" in header   # 1600m requests
    assert "6.00 cores" in header   # 6000m limits
    assert "3.31Gi" in header       # 3392Mi requests


# --- detection (text_is_generated_output) ---------------------------------

def test_generated_output_is_detected():
    header = format_output_header(command="customize-daemonset", totals=TOTALS)
    text = header + "---\napiVersion: apps/v1\nkind: DaemonSet\n"
    assert text_is_generated_output(text) is True


def test_plain_manifest_is_not_detected():
    text = "apiVersion: apps/v1\nkind: DaemonSet\nmetadata:\n  name: agent\n"
    assert text_is_generated_output(text) is False
